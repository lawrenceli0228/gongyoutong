"""``agents/cad/levels.py`` 的守门断言 —— 由图上标高推算层高。

这一组全是**纯函数**测试:不联网、不碰盘、不调模型,所以跑得飞快,
也因此可以把边界一条条钉死。判据的来处是 2026-09-21 那次线上体验测试:
用户问「幼儿园立面的层高」,图上写着 ±0.000 / 3.300 / 6.600 / 9.900 …,
而模型照尺寸红线拒答了。对着原图核过 —— 层高就是 3.300。

🔴 本文件最要紧的不是「算得对」,是**「算不出的时候别硬给」**:
   下半截那几条(一层楼、层层不等高、标高没认全)守的都是这个。
   把 `derive_floor_heights` 的 `return None` 改成「挑个最像的」,
   上半截照样全绿,只有下半截会红。
"""

from __future__ import annotations

import pytest

from gyt.agents.cad import levels

# 2026-09-21 那张幼儿园立面,视觉模型认出来的原样(节选 —— 混着尺寸/轴号/比例,
# 就是为了让测试跟真实输入一样脏)。真值以 PDF 原图核过:层高 3.300。
真实立面文字 = [
    "上图左侧标高: 20.300",
    "上图左侧标高: 14.200",
    "上图左侧标高: 12.700",
    "上图左侧标高: 9.900",
    "上图左侧标高: 6.600",
    "上图标高: 3.300",
    "上图标高: ±0.000",
    "上图标高: -0.300",
    "上图左侧标高: -0.450",
    "上图左侧尺寸: 3300",
    "上图左侧尺寸: 1200",
    "上图比例: 1:100",
    "上图轴号: ㉑",
    "上图索引: 1/13",
]


def test_真实立面_推出的层高是3米3() -> None:
    """这一条就是那次线上体验测试的回归:同样的输入,现在必须给得出 3.300。"""
    结果 = levels.derive_floor_heights(真实立面文字)

    assert 结果 is not None, "图上标高够推层高了,不该再拒答"
    assert 结果["typical"] == 3.3
    assert 结果["typical_count"] == 3  # ±0.000→3.300→6.600→9.900,连着三层


def test_标高认得出_尺寸链上的整数毫米不会被误当标高() -> None:
    """`3300`(尺寸链,毫米)和 `3.300`(标高,米)必须分得开。

    分不开的坏法很具体:3300 被当成标高之后,它和 20.300 之间差了三千多米,
    整串差值全乱,`typical` 可能变成某个荒唐的数 —— 而它看着仍然是个「数」。
    正则要求小数点后**恰好三位**,正是为了这件事。
    """
    assert levels.parse_elevations(真实立面文字) == [
        -0.45,
        -0.3,
        0.0,
        3.3,
        6.6,
        9.9,
        12.7,
        14.2,
        20.3,
    ]


def test_比例与索引里的数字不许混进标高() -> None:
    """`1:100`、`1/13`、`2026.09.21` 这类图签上的数字不是标高。"""
    assert levels.parse_elevations(["比例 1:100", "索引 1/13", "日期 2026.09.21"]) == []


@pytest.mark.parametrize(
    ("写法", "期望"),
    [
        ("±0.000", 0.0),
        ("+3.300", 3.3),
        ("-0.450", -0.45),
        ("标高:12.700", 12.7),
    ],
)
def test_标高的四种写法都认(写法: str, 期望: float) -> None:
    assert levels.parse_elevations([写法]) == [期望]


def test_同一标高在图上写了两遍_只算一次() -> None:
    """立面左右两侧各标一遍是常态。不去重的话 `steps` 里会冒出一堆 0 米高差。"""
    assert levels.parse_elevations(["左 3.300", "右 3.300", "±0.000"]) == [0.0, 3.3]


def test_同一张图上两套标高_不许跨着凑出假层高() -> None:
    """🔴 这条是 2026-09-21 接线后**实测抓到的真 bug**,合成用例当时全绿。

    那张幼儿园立面上有两套标高:左侧主楼 ±0.000/3.300/6.600/9.900…,
    右侧裙房 ±0.000/3.300/7.200/10.000。混排成一串之后

        …6.600 7.200 9.900 10.000 12.700…
    差        0.600 2.700  0.100  2.700

    两个 2.700 是**跨着两栋楼凑出来的**,楼里并不存在这么一层。按「重复几次」判定时
    它和 3.300 都是两次,并列时取矮的 —— 于是答出 2.700,一个错的层高。
    改用「相邻档位上连续出现」之后:3.300 连着两档,而那两个 2.700 各自孤立。

    ⚠️ 别把这条用例简化成「只留几个数」——**必须保留两套标高交错**的形状,
       那正是 bug 的成因;拆开测就再也抓不到了。
    """
    两套 = ["-0.450", "-0.300", "±0.000", "3.300", "6.600", "7.200", "9.900",
            "10.000", "12.700", "14.200", "20.300"]

    结果 = levels.derive_floor_heights(两套)

    assert 结果 is not None
    assert 结果["typical"] == 3.3, f"跨体量凑出来的差值又被当成层高了:{结果['typical']}"


def test_两段一样长层高却不同_不许替人挑一个() -> None:
    """一栋楼两个体量各自成系统(一边 3.000 两层、一边 3.600 两层)时,
    「标准层高」这说法本身就不成立。报哪个都是替人做判断,如实回 None。
    """
    assert levels.derive_floor_heights(
        ["±0.000", "3.000", "6.000", "50.000", "53.600", "57.200"]
    ) is None


# --- 下半截:**推不出就别给** -------------------------------------------------


def test_只有一层_推不出层高() -> None:
    """单层房子只有 ±0.000 与屋面标高,一个差值,凑不出「重复」—— 必须回 None。"""
    assert levels.derive_floor_heights(["±0.000", "4.200"]) is None


def test_层层不等高_推不出标准层高() -> None:
    """每层都不一样高(3.0 / 3.6 / 4.2)时没有「标准层高」这回事,不许挑一个报。"""
    assert levels.derive_floor_heights(["±0.000", "3.000", "6.600", "10.800"]) is None


def test_室内外高差与女儿墙不许被当成层高() -> None:
    """0.150 / 0.300 / 1.500 这些差值落在合理层高区间外,连候选都不该是。

    ⚠️ 这条和上一条不一样:这里**有**重复(0.150 出现两次),
    拿掉区间判据的话它会被当成「标准层高 0.15 米」报出去。
    """
    assert levels.derive_floor_heights(["-0.450", "-0.300", "±0.000", "1.500"]) is None


def test_一个标高都没认出来_回None() -> None:
    assert levels.derive_floor_heights(["轴号 ㉑", "比例 1:100"]) is None


# --- 说给人听的那句话 --------------------------------------------------------


def test_报层高时必须同时说出处和那句免责() -> None:
    """🔴 数、出处、「不是图上直接标的」——三样缺一不可。

    缺了出处,工友没法对图复核;缺了那句免责,他会以为图纸上就写着这个数。
    当初宁可拒答,守的就是这个;现在给数了,这句话就是新的守门人。
    """
    结果 = levels.derive_floor_heights(真实立面文字)
    assert 结果 is not None
    话 = levels.describe_floor_heights(结果)

    assert "3.300" in 话
    assert "±0.000→3.300→6.600→9.900" in 话, "要能看出这个数是从哪几档标高数出来的"
    assert "不是图纸上直接标的" in 话
    assert "以原图为准" in 话


def test_不连续的同层高不许被串成一条假楼梯() -> None:
    """主楼 3.300、另一头裙房也 3.300,中间隔着别的高差 —— 不许用「→」连起来。

    串起来的话读的人会以为中间那几档也是这个层高,而那是图上没有的东西。
    只报最长的那一段连续的,其余进「其余几档」。
    """
    结果 = levels.derive_floor_heights(["±0.000", "3.300", "6.600", "11.500", "14.800"])
    assert 结果 is not None
    话 = levels.describe_floor_heights(结果)

    assert "±0.000→3.300→6.600" in 话
    assert "11.500→14.800" not in 话.split("其余")[0], "不连续的那档不该出现在楼梯里"
