/** 简体侧独有字。由 SCRIPT_PAIRS 派生 —— 不许手写第二份。 */
export const HANS_CHARS: ReadonlySet<string> = new Set(
  SCRIPT_PAIRS.map((p) => p[0]),
);

/** 繁體侧独有字。同上派生。 */
export const HANT_CHARS: ReadonlySet<string> = new Set(
  SCRIPT_PAIRS.map((p) => p[1]),
);

/** 拉丁字母占比超过这个数就判成英文。0.5 = 一半以上是字母。 */
const LATIN_RATIO_THRESHOLD = 0.5;

const LATIN_RE = /[A-Za-z]/;
const HAN_RE = /[一-鿿]/;

/**
 * 判一段用户输入是什么语种;判不出来返回 null。
 *
 * ```
 * 有汉字?
 *   ├─ 是 → 数简体独有字 vs 繁體独有字,多的那边赢;打平或都是 0 → null
 *   └─ 否 → 拉丁字母占比 > 阈值 → "en";否则 null(纯数字、纯符号、空串)
 * ```
 *
 * **判不出来是常态,不是异常**:「好」「收到」「拍好了」在简繁里逐字相同,
 * 8 类违规项里也有一半同形(未戴安全帽、消防通道堵塞)。所以调用方必须
 * 走 resolveLang 的兜底链,别直接拿 null 当英文或当默认。
 */
export function detectInput(text: string): Lang | null {
  const s = text ?? "";
  if (!s) return null;

  if (HAN_RE.test(s)) {
    let hans = 0;
    let hant = 0;
    for (const ch of s) {
      if (HANS_CHARS.has(ch)) hans += 1;
      else if (HANT_CHARS.has(ch)) hant += 1;
    }
    if (hans > hant) return "zh-Hans";
    if (hant > hans) return "zh-Hant";
    return null; // 打平(含两边都是 0):判不出来,交给兜底链
  }

  const letters = [...s].filter((c) => LATIN_RE.test(c)).length;
  const meaningful = [...s].filter((c) => !/\s/.test(c)).length;
  if (meaningful > 0 && letters / meaningful > LATIN_RATIO_THRESHOLD) return "en";
  return null;
}

/**
 * 定出本回合该用的语种。三层,**三层都要**(方案 §3.1)。
 *
 * ```
 * 显式选择(用户点过切换器)          ← 第一顺位
 *         │ 没点过
 *         ▼
 * 往回扫本线程的用户发言(新 → 旧)    ← 「第二句只打好」靠它
 *         │ 全线程判不出来
 *         ▼
 * DEFAULT_LANG
 * ```
 *
 * 🔴 **顺序不许反。** 只有第二层的话,这个场景会错:用户全程简体聊了十轮,
 *    点了 English 切换器,再打「ok」—— 往回扫找到十轮简体,用简体答,
 *    **把用户的显式选择覆盖掉了**。用户按了按钮而系统当没看见,
 *    比语言判错更糟。
 *
 * @param explicit          用户在界面上选过的语种;没选过传 null
 * @param userTextsNewestFirst 本线程的用户发言,**从新到旧**
 */
export function resolveLang(
  explicit: Lang | null,
  userTextsNewestFirst: readonly string[],
): Lang {
  if (explicit) return explicit;
  for (const t of userTextsNewestFirst) {
    const hit = detectInput(t);
    if (hit) return hit;
  }
  return DEFAULT_LANG;
}

