/** 消息角色。只有这两种参与判定 —— 工具结果不进 markdown 渲染路径。 */
export type MessageRole = "human" | "ai";

/**
 * 这条消息要不要做 简→繁 转换。
 *
 * 两条硬约束,都不许放宽:
 *
 * 🔴 **用户发言恒 false。** human.tsx:114 的 refPattern 抓的是
 *    `(照片编号:…)` / `(图纸编号:…)`,那段是后端 uploads.py 拼进去的**简体**。
 *    转了就变成「照片編號」,正则匹配不上 → **照片不渲染成图,退回一段裸 hex**,
 *    而且零报错。human.tsx 的头注还专门写着「照片和图纸是两个词,不许串」。
 *
 * 🔴 **目标语不是繁體时原样返回。** 简体是模型的原生输出,转它是空转;
 *    英文那条路走提示词不走转换(第二批)。这条同时保证了
 *    **简体用户一个字节的 opencc 都不下载**(懒加载的触发点就是这里)。
 */
export function shouldConvert(role: MessageRole, target: Lang): boolean {
  if (role === "human") return false;
  return target === "zh-Hant";
}

